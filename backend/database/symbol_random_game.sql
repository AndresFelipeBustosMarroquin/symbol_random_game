CREATE DATABASE symbol_random_game
WITH OWNER = postgres ENCODING = 'UTF8';

\c symbol_random_game;

CREATE TYPE momento_mensaje AS ENUM ('inicio','fin','pausa');

CREATE TABLE usuario (
    id_usuario SERIAL PRIMARY KEY,
    nombre_uso VARCHAR(50) NOT NULL UNIQUE,
    contrasena_us VARCHAR(255) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    descripcion VARCHAR(180) NOT NULL DEFAULT '',
    avatar VARCHAR(24) NOT NULL DEFAULT 'astronauta'
);

CREATE TABLE avatar (
    id_avatar SERIAL PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    imagen_url VARCHAR(255) NOT NULL
);

CREATE TABLE paleta (
    id_paleta SERIAL PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    color_primario VARCHAR(7) NOT NULL,
    color_secundario VARCHAR(7) NOT NULL,
    color_fondo VARCHAR(7) NOT NULL
);

CREATE TABLE modo_juego (
    id_modo SERIAL PRIMARY KEY,
    nombre_modo VARCHAR(50) NOT NULL,
    descripcion VARCHAR(255)
);

CREATE TABLE nivel (
    id_nivel SERIAL PRIMARY KEY,
    id_modo INT NOT NULL REFERENCES modo_juego(id_modo) ON UPDATE CASCADE ON DELETE CASCADE,
    nombre_nivel VARCHAR(50) NOT NULL,
    digitos_base INT NOT NULL,
    tiempo_base INT NOT NULL,
    vidas_base INT NOT NULL,
    UNIQUE(id_modo,digitos_base,tiempo_base,vidas_base)
);

CREATE TABLE mensaje (
    id_mensaje SERIAL PRIMARY KEY,
    id_nivel INT NOT NULL REFERENCES nivel(id_nivel) ON UPDATE CASCADE ON DELETE CASCADE,
    contenido VARCHAR(255) NOT NULL,
    momento momento_mensaje NOT NULL DEFAULT 'inicio'
);

CREATE TABLE configuraciones (
    id_configuracion SERIAL PRIMARY KEY,
    sonido INT NOT NULL DEFAULT 0,
    vidas_co INT NOT NULL,
    digitos_co INT NOT NULL,
    id_paleta INT NOT NULL REFERENCES paleta(id_paleta),
    id_avatar INT NOT NULL REFERENCES avatar(id_avatar),
    id_usuario INT NOT NULL UNIQUE REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    tiempo_co INT NOT NULL DEFAULT 5,
    volumen DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    fuente INT NOT NULL DEFAULT 0
);

CREATE TABLE partida (
    id_partida SERIAL PRIMARY KEY,
    id_usuario INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_modo INT NOT NULL REFERENCES modo_juego(id_modo),
    id_nivel INT NOT NULL REFERENCES nivel(id_nivel),
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP,
    resultado INT
);

CREATE TABLE puntuacion (
    id_puntuacion SERIAL PRIMARY KEY,
    nivel VARCHAR(50) NOT NULL,
    digitos INT NOT NULL,
    vidas_pun INT NOT NULL,
    tiempo_pregunta INT NOT NULL,
    tiempo_total INT NOT NULL,
    resultado INT NOT NULL,
    id_usuario INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_partida INT NOT NULL UNIQUE REFERENCES partida(id_partida) ON DELETE CASCADE
);

CREATE TABLE ranking (
    id_ranking SERIAL PRIMARY KEY,
    id_usuario INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_modo INT NOT NULL REFERENCES modo_juego(id_modo) ON DELETE CASCADE,
    id_nivel INT NOT NULL REFERENCES nivel(id_nivel) ON DELETE CASCADE,
    mejor_puntaje INT NOT NULL DEFAULT 0,
    promedio_puntaje NUMERIC(10,2) NOT NULL DEFAULT 0,
    fecha_actualizacion TIMESTAMP NOT NULL,
    UNIQUE(id_usuario,id_modo,id_nivel)
);

CREATE TABLE resena_perfil (
    id_resena INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_autor INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_perfil INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    contenido VARCHAR(500) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(id_autor,id_perfil),
    CHECK(id_autor <> id_perfil),
    CHECK(length(trim(contenido)) > 0)
);

CREATE TABLE amistad (
    id_usuario_menor INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_usuario_mayor INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_solicitante INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    estado VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE',
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(id_usuario_menor,id_usuario_mayor),
    CHECK(id_usuario_menor < id_usuario_mayor),
    CHECK(id_solicitante = id_usuario_menor OR id_solicitante = id_usuario_mayor),
    CHECK(estado IN ('PENDIENTE','ACEPTADA'))
);

CREATE TABLE chat_mensaje (
    id_mensaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_emisor INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_receptor INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    contenido VARCHAR(1000) NOT NULL,
    fecha_envio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK(id_emisor <> id_receptor),
    CHECK(length(trim(contenido)) > 0)
);

CREATE INDEX ix_chat_participantes ON chat_mensaje(id_emisor,id_receptor,fecha_envio);
CREATE INDEX ix_partida_usuario ON partida(id_usuario,fecha_fin DESC);
CREATE INDEX ix_puntuacion_resultado ON puntuacion(resultado DESC);
CREATE INDEX ix_amistad_solicitudes ON amistad(id_solicitante,estado,fecha_actualizacion DESC);
CREATE INDEX ix_resena_perfil ON resena_perfil(id_perfil,fecha_creacion DESC);
CREATE INDEX ix_chat_receptor ON chat_mensaje(id_receptor,id_emisor,fecha_envio);